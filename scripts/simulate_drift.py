#!/usr/bin/env python3
"""Compare the training-period distribution with a drifted period and
write eval/drift_report.json/.md. Detected shift != accuracy loss."""
import json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from fraudwatch.drift import drift_report
from fraudwatch.generator import generate

ROOT = Path(__file__).resolve().parents[1]


def main():
    ref = generate(n=20000, seed=42, drift=False)
    cur = generate(n=8000, seed=123, drift=True, start="2025-07-01")
    rep = drift_report(ref, cur)
    rep["reference"] = "training distribution, seed 42, n=20000"
    rep["current"] = "drifted period, seed 123, n=8000 (amounts x1.6, online/crypto/travel share up)"
    (ROOT / "eval" / "drift_report.json").write_text(json.dumps(rep, indent=2))
    lines = ["# Drift report (generated by scripts/simulate_drift.py)", "",
             "| feature | PSI | level |", "|---|---|---|"]
    for f, r in rep["per_feature_psi"].items():
        lines.append(f"| {f} | {r['psi']} | {r['level']} |")
    lines += ["", f"Drift detected: **{rep['drift_detected']}** on {rep['significant_features']}", "",
              rep["interpretation"]]
    (ROOT / "eval" / "drift_report.md").write_text("\n".join(lines) + "\n")
    print(json.dumps(rep, indent=2))


if __name__ == "__main__":
    main()
